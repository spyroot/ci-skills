def _action(
    cluster: MemoryCluster, selected: Namespace, *, deleting: bool = False
) -> WorkflowAction:
    """Bind a real workflow action to the existing in-memory Kubernetes service.

    :param cluster: Offline namespace storage and mutation journal.
    :param selected: Identity generated by the test's single setup fixture.
    :param deleting: Whether the caller selects the existing delete action.
    :returns: Minimal real action accepted by the namespace callbacks.
    """
    action = WORKFLOWS.WorkflowAction(
        Namespace(
            action=DELETE_OPERATION if deleting else CREATE_OPERATION,
            namespace=selected.namespace,
            name=selected.operation,
            timeout=COMMAND_TIMEOUT,
        )
    )
    action.runner = RUNNER.RunnerAction(
        namespace=selected.namespace,
        name=selected.operation,
        source_root=RUNNER.RUNTIME_ROOT,
        labels=(),
        timeout=COMMAND_TIMEOUT,
    )
    action.context.kubernetes = cluster
    action.repository_identity = IDENTITY.resolve_repository(selected.repository)
    action.resolved_runner_name = IDENTITY.ResolvedName(
        selected.operation, IDENTITY.NameSource.EXPLICIT
    )
    action.target = SimpleNamespace(
        github=TARGET.GitHubTarget(selected.host, selected.repository)
    )
    return action


def _namespace(selected: Namespace, *, owned: bool) -> JSONObject:
    """Build native namespace state with explicit borrowed or owned metadata.

    :param selected: Identity generated once for this complete resource lifecycle.
    :param owned: Whether the namespace carries the operation's ownership labels.
    :returns: Native read-back fixture with its immutable namespace UID.
    """
    labels = (
        {
            RESOURCES.MANAGER_LABEL: RESOURCES.MANAGER_VALUE,
            RESOURCES.OPERATION_LABEL: selected.operation,
        }
        if owned
        else {}
    )
    return {
        FIELD_API_VERSION: API_VERSION,
        FIELD_KIND: NAMESPACE_KIND,
        FIELD_METADATA: {
            FIELD_NAME: selected.namespace,
            FIELD_UID: selected.uid,
            FIELD_LABELS: labels,
        },
    }


def test_missing_explicit_namespace_blocks_without_kubernetes_mutation(
    selected_scope: Namespace,
) -> None:
    """Stop before mutation when a caller-selected namespace does not exist.

    :param selected_scope: Generated selection that remains absent in the cluster.
    """
    cluster = MemoryCluster()
    action = _action(cluster, selected_scope)
    callback = NAMESPACES.ObserveGitHubNamespace(action)
    callback.bind(action.context)
    with pytest.raises(
        KUBERNETES.KubernetesError, match=NAMESPACES.EXPLICIT_NAMESPACE_MISSING
    ):
        callback.run()
    assert cluster.applied == []
    assert cluster.deleted == []
    assert action.context.runner_scopes == {}


def test_deleting_runner_preserves_borrowed_namespace_and_uid(
    selected_scope: Namespace,
) -> None:
    """Leave a caller-owned namespace present after runner deletion.

    :param selected_scope: Generated namespace reused throughout deletion and read-back.
    """
    selected = selected_scope
    cluster = MemoryCluster()
    cluster.objects[selected.namespace_key] = _namespace(selected, owned=False)
    action = _action(cluster, selected, deleting=True)
    before = NAMESPACES.ObserveGitHubNamespace(action)
    before.bind(action.context)
    before.run()
    deletion = NAMESPACES.DeleteGitHubNamespace(action)
    deletion.bind(action.context)
    assert deletion.run()[FIELD_VERIFIED] is True
    observed = next(iter(action.context.runner_scopes.values()))
    assert observed.uid == selected.uid
    assert observed.ownership == SCOPES.ScopeOwnership.BORROWED
    assert observed.state == SCOPES.ScopeState.PRESENT
    assert observed.retention == SCOPES.ScopeRetention.PRESERVED
    assert cluster.objects[selected.namespace_key] == _namespace(selected, owned=False)
    assert cluster.applied == []
    assert cluster.deleted == []


def test_namespace_replacement_blocks_deletion_of_new_uid(
    selected_scope: Namespace,
) -> None:
    """Refuse deletion after the selected namespace has been replaced.

    :param selected_scope: Original and replacement identities generated once by setup.
    """
    selected = selected_scope
    cluster = MemoryCluster()
    cluster.objects[selected.namespace_key] = _namespace(selected, owned=True)
    action = _action(cluster, selected, deleting=True)
    before = NAMESPACES.ObserveGitHubNamespace(action)
    before.bind(action.context)
    before.run()
    replacement = _namespace(selected, owned=True)
    replacement[FIELD_METADATA][FIELD_UID] = selected.replacement_uid
    cluster.objects[selected.namespace_key] = replacement
    deletion = NAMESPACES.DeleteGitHubNamespace(action)
    deletion.bind(action.context)
    with pytest.raises(
        KUBERNETES.KubernetesError, match=NAMESPACES.NAMESPACE_UID_CHANGED
    ):
        deletion.run()
    assert cluster.objects[selected.namespace_key] == replacement
    assert cluster.deleted == []


def test_created_namespace_cleanup_refuses_replacement_uid(
    selected_scope: Namespace,
) -> None:
    """Keep a replacement namespace intact during cleanup of the original creation.

    :param selected_scope: Generated original and replacement identities.
    """
    selected = selected_scope
    cluster = MemoryCluster()
    resources = RESOURCES.ResourceSet(cluster, CLUSTER_NAMESPACE, selected.operation)
    created = resources.apply(
        {
            FIELD_API_VERSION: API_VERSION,
            FIELD_KIND: NAMESPACE_KIND,
            FIELD_METADATA: {FIELD_NAME: selected.namespace},
        }
    )
    created_uid = created[FIELD_UID]
    assert isinstance(created_uid, str)
    replacement = _namespace(selected, owned=True)
    replacement[FIELD_METADATA][FIELD_UID] = selected.replacement_uid
    cluster.objects[selected.namespace_key] = replacement
    with pytest.raises(KUBERNETES.KubernetesError, match=DELETE_IDENTITY_CHANGED):
        resources.cleanup_created(
            expected_uids={(NAMESPACE_KIND, selected.namespace): created_uid}
        )
    assert cluster.objects[selected.namespace_key] == replacement
    assert cluster.deleted == []
    assert resources.created == [(NAMESPACE_KIND, selected.namespace)]


@pytest.mark.parametrize("removed", (True, False))
def test_owned_namespace_delete_binds_uid_and_requires_absence_readback(
    monkeypatch: pytest.MonkeyPatch, selected_scope: Namespace, removed: bool
) -> None:
    """Delete the observed owned object and reject a provider no-effect result.

    :param monkeypatch: Replace native deletion while retaining real ownership logic.
    :param selected_scope: Generated exact namespace identity and UID precondition.
    :param removed: Whether the provider actually removes the selected namespace.
    """
    selected = selected_scope
    cluster = MemoryCluster()
    cluster.objects[selected.namespace_key] = _namespace(selected, owned=True)
    action = _action(cluster, selected, deleting=True)
    before = NAMESPACES.ObserveGitHubNamespace(action)
    before.bind(action.context)
    before.run()
    native_delete = Mock(wraps=cluster.delete) if removed else Mock()
    monkeypatch.setattr(cluster, cluster.delete.__name__, native_delete)
    deletion = NAMESPACES.DeleteGitHubNamespace(action)
    deletion.bind(action.context)
    if removed:
        assert deletion.run()[FIELD_VERIFIED] is True
        observed = next(iter(action.context.runner_scopes.values()))
        assert observed.uid == selected.uid
        assert observed.state == SCOPES.ScopeState.ABSENT
        assert observed.cleanup_status == STATUS.PASS
        assert selected.namespace_key not in cluster.objects
    else:
        with pytest.raises(KUBERNETES.KubernetesError):
            deletion.run()
        assert selected.namespace_key in cluster.objects
    native_delete.assert_called_once_with(
        NAMESPACE_KIND, selected.namespace, CLUSTER_NAMESPACE, expected_uid=selected.uid
    )
    assert cluster.applied == []


def test_gitlab_runner_protection_mismatch_fails_after_independent_reads(
    selected_scope: Namespace,
) -> None:
    """Reject a runner whose actual protection differs from the explicit choice.

    :param selected_scope: Generated provider project, runner and description identity.
    """
    selected = selected_scope
    plan = replace(
        _plan(GET_OPERATION, {}, selected.runner_id),
        target_reference=str(selected.project_id),
    )
    endpoint = RUNNER_RESOURCE.format(runner_id=selected.runner_id)
    membership = SCOPED_RUNNERS.format(project_id=selected.project_id)
    api = FakeAPI(
        {
            (GET_METHOD, endpoint): [
                _runner(
                    selected.runner_id,
                    description=selected.operation,
                    tag_list=[selected.tag],
                    projects=[{FIELD_ID: selected.project_id}],
                )
            ],
            (GET_METHOD, membership): [[{FIELD_ID: selected.runner_id}]],
        }
    )
    with pytest.raises(RUNNERS.ActionError, match=OPTIONS.PROTECTION_READBACK_MISMATCH):
        RUNNERS.read_runner_record(
            api,
            _bound_session(plan),
            PROJECT_KIND,
            selected.project_id,
            selected.runner_id,
            expected_protection=OPTIONS.RunnerProtection.UNPROTECTED,
        )
    assert api.calls == [(GET_METHOD, endpoint), (GET_METHOD, membership)]


@pytest.mark.parametrize("repository_matches", (True, False))
@pytest.mark.parametrize("hashed_operation", (False, True))
def test_github_workflow_binds_deferred_consumers_to_verified_custom_identity(
    monkeypatch: pytest.MonkeyPatch,
    selected_scope: Namespace,
    repository_matches: bool,
    hashed_operation: bool,
) -> None:
    """Reuse a custom name only after matching its native repository and ownership.

    :param monkeypatch: Replace provider writes while retaining real workflow ordering.
    :param selected_scope: Generated selected, existing and alternate repository identities.
    :param repository_matches: Whether the observed Deployment belongs to this repo.
    :param hashed_operation: Native current ownership hash or legacy workload-name label.
    """
    selected = selected_scope
    cluster = MemoryCluster()
    action = _action(cluster, selected)
    action.args.kind = GITHUB_KIND
    action.args.name = selected.legacy_name
    action.args.label = [selected.tag]
    action.args.runner_root = RUNNER.RUNTIME_ROOT
    action._workload()
    native_operation = (
        action.runner.operation if hashed_operation else selected.legacy_name
    )
    action.args.action = UPDATE_OPERATION
    action.args.namespace = None
    action.args.name = None
    action.args.apply = True
    action._workload()
    planned_namespace = action.runner.namespace
    planned_operation = action.runner.operation
    planned_name = action.runner.name
    action.spec = SimpleNamespace(
        image_repository=selected.repository,
        image_tag=selected.tag,
        namespace=planned_namespace,
    )
    native_namespace = _namespace(selected, owned=True)
    native_namespace[FIELD_METADATA][FIELD_LABELS][RESOURCES.OPERATION_LABEL] = (
        native_operation
    )
    cluster.objects[selected.namespace_key] = native_namespace
    deployment = {
        FIELD_KIND: NAMESPACES.DEPLOYMENT_KIND,
        FIELD_METADATA: {FIELD_NAME: selected.legacy_name},
        NAMESPACES.SPEC_FIELD: {
            NAMESPACES.TEMPLATE_FIELD: {
                NAMESPACES.SPEC_FIELD: {
                    NAMESPACES.INIT_CONTAINERS_FIELD: [
                        {
                            NAMESPACES.ENVIRONMENT_FIELD: [
                                {
                                    FIELD_NAME: NAMESPACES.RUNNER_REPOSITORY_ENV,
                                    NAMESPACES.ENV_VALUE_FIELD: (
                                        selected.repository
                                        if repository_matches
                                        else selected.alternate_repository
                                    ),
                                },
                                {
                                    FIELD_NAME: NAMESPACES.RUNNER_HOST_ENV,
                                    NAMESPACES.ENV_VALUE_FIELD: selected.host,
                                },
                            ]
                        }
                    ]
                }
            }
        },
    }
    cluster.objects[
        (
            NAMESPACES.DEPLOYMENT_KIND.casefold(),
            selected.namespace,
            selected.legacy_name,
        )
    ] = RESOURCES.ResourceSet(cluster, selected.namespace, native_operation).managed(
        deployment
    )
    for callback_type in (
        GITHUB_COMMAND.K8SAuth,
        GITHUB_COMMAND.GitHubAuth,
        GITHUB_COMMAND.HarborAuth,
        GITHUB_COMMAND.ConfirmWorkflow,
        GITHUB_COMMAND.EnsureNamespace,
        GITHUB_COMMAND.HarborBuild,
        GITHUB_COMMAND.HarborPush,
    ):
        monkeypatch.setattr(
            GITHUB_COMMAND,
            callback_type.__name__,
            lambda *_args, **_kwargs: CALLBACKS.LocalCallback(action),
        )
    consumers = (
        GITHUB_COMMAND.PullImage,
        GITHUB_COMMAND.GitHubRunnerRuntime,
        GITHUB_COMMAND.DeployRunner,
        GITHUB_COMMAND.CreateGitHubRunner,
    )
    captured: list[RUNNER.RunnerAction] = []

    def capture(runner: RUNNER.RunnerAction) -> CALLBACKS.LocalCallback:
        """Capture the action selected when the real deferred adapter collects.

        :param runner: Current resolved runner action supplied by the workflow factory.
        :returns: Nonmutating local callback bound to that exact action.
        """
        captured.append(runner)
        return CALLBACKS.LocalCallback(runner)

    for callback_type in consumers:
        monkeypatch.setattr(GITHUB_COMMAND, callback_type.__name__, capture)
    executor = GITHUB_COMMAND.workflow(action)
    assert captured == []
    if repository_matches:
        executor.run()
        assert captured == [action.runner] * len(consumers)
    else:
        with pytest.raises(KUBERNETES.KubernetesError, match=UPDATE_IDENTITY_MISSING):
            executor.run()
        assert captured == []
    assert action.runner.namespace == (
        selected.namespace if repository_matches else planned_namespace
    )
    assert action.runner.name == (
        selected.legacy_name if repository_matches else planned_name
    )
    assert action.runner.operation == (
        native_operation if repository_matches else planned_operation
    )
    assert action.resolved_runner_name.source == (
        IDENTITY.NameSource.PROVIDER
        if repository_matches
        else IDENTITY.NameSource.REPOSITORY
    )
    assert cluster.objects[selected.namespace_key] == native_namespace
    assert cluster.applied == cluster.deleted == []


@pytest.mark.parametrize("preexisting", (False, True), ids=("created", "borrowed"))
def test_successful_build_namespace_cleanup_preserves_interleaved_consumer(
    selected_scope: Namespace, preexisting: bool
) -> None:
    """Keep a configured build namespace usable by a second application.

    :param selected_scope: Shared baseline identity fields copied for each workflow.
    :param preexisting: Single initial-state change: namespace already present or absent.
    """
    baseline = tuple(vars(selected_scope).items())
    selected = Namespace(**dict(baseline))
    cluster = MemoryCluster()
    if preexisting:
        cluster.objects[selected.namespace_key] = _namespace(selected, owned=False)
    workflows = []
    temporary_resources = []
    temporary_documents = []
    for app in (selected.operation, selected.legacy_name):
        inputs = Namespace(**dict(baseline))
        inputs.operation = app
        action = _action(cluster, inputs)
        action.args.kind = GITHUB_KIND
        action.args.namespace = None
        action.args.label = [selected.tag]
        action.args.runner_root = RUNNER.RUNTIME_ROOT
        action.spec = SimpleNamespace(app=app, namespace=selected.namespace)
        action._workload()
        namespace = WORKFLOWS.EnsureNamespace(action)
        namespace.bind(action.context)
        assert namespace.run()[FIELD_VERIFIED] is True
        resources = RESOURCES.ResourceSet(
            cluster, selected.namespace, action.runner.operation
        )
        document = {
            FIELD_API_VERSION: API_VERSION,
            FIELD_KIND: CONFIG_MAP_KIND,
            FIELD_METADATA: {FIELD_NAME: app},
            FIELD_DATA: {FIELD_APP: app},
        }
        resources.apply(document)
        workflows.append((action, namespace))
        temporary_resources.append(resources)
        temporary_documents.append(document)
    (first, first_namespace), (second, second_namespace) = workflows
    first_resources, second_resources = temporary_resources
    first_key = (CONFIG_MAP_KIND.casefold(), selected.namespace, selected.operation)
    second_before = cluster.read(
        CONFIG_MAP_KIND, selected.legacy_name, selected.namespace
    )
    namespace_before = cluster.read(
        NAMESPACE_KIND, selected.namespace, CLUSTER_NAMESPACE
    )
    assert namespace_before is not None
    assert second_before is not None
    assert first.runner.operation != second.runner.operation
    assert first.spec.namespace == second.spec.namespace == selected.namespace
    build_key = NAMESPACES.scope_key(SCOPES.ScopePurpose.BUILD, selected.namespace)
    first_build = first.context.runner_scopes[build_key]
    second_build = second.context.runner_scopes[build_key]
    assert second_build.ownership == SCOPES.ScopeOwnership.BORROWED
    assert second_build.retention == SCOPES.ScopeRetention.PRESERVED
    assert first.context.failed is False
    first_resources.cleanup_created()
    assert first_key not in cluster.objects
    assert cluster.deleted == [first_key]
    remaining = dict(cluster.objects)

    first_namespace.cleanup()

    assert (
        cluster.read(NAMESPACE_KIND, selected.namespace, CLUSTER_NAMESPACE)
        == namespace_before
    ), first_build.document()
    assert cluster.objects == remaining
    assert cluster.deleted == [first_key]
    assert second_namespace.run()[FIELD_VERIFIED] is True
    assert (
        cluster.read(CONFIG_MAP_KIND, selected.legacy_name, selected.namespace)
        == second_before
    )
    reused = second_resources.apply(temporary_documents[-1])
    assert reused[FIELD_ACTION] == STATUS.NO_OP
    assert reused[FIELD_UID] == second_before[FIELD_METADATA][FIELD_UID]
    assert first_build.ownership == (
        SCOPES.ScopeOwnership.BORROWED
        if preexisting
        else SCOPES.ScopeOwnership.OPERATION_OWNED
    )
    assert first_build.retention == (
        SCOPES.ScopeRetention.PRESERVED
        if preexisting
        else SCOPES.ScopeRetention.RETAINED
    )
    assert tuple(vars(selected_scope).items()) == baseline
